const FA_DIGITS = '۰۱۲۳۴۵۶۷۸۹';
const AR_DIGITS = '٠١٢٣٤٥٦٧٨٩';

export function normalize(text) {
  return String(text)
    .toLowerCase()
    .replace(/[۰-۹]/g, (d) => FA_DIGITS.indexOf(d))
    .replace(/[٠-٩]/g, (d) => AR_DIGITS.indexOf(d))
    .replace(/ك/g, 'ک')
    .replace(/ي/g, 'ی')
    .replace(/\u200c/g, ' ')
    .trim();
}

export function searchProducts(list, query) {
  const q = normalize(query);
  if (!q) return list;
  return list.filter((p) => {
    const haystack = normalize([
      p.name, p.brand, p.sku, p.short,
      p.voltage ? `${p.voltage} ولت` : '',
      p.current ? `${p.current} آمپر` : '',
      p.wattage ? `${p.wattage} وات` : '',
    ].join(' '));
    return q.split(/\s+/).every((term) => haystack.includes(term));
  });
}

export function getProduct(slug) {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getRelated(product, limit = 4) {
  const same = PRODUCTS.filter((p) => p.id !== product.id &&
    p.categories.some((c) => product.categories.includes(c)));
  const others = PRODUCTS.filter((p) => p.id !== product.id &&
    !same.includes(p) && p.inStock);
  return [...same, ...others].slice(0, limit);
}
